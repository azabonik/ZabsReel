// Builds the clean-room runtime (packages/motion/cleanroom/runtime/src) into
// ONE page script, dist/zr-runtime.js (MOTION-PLAN D1, D5). There is no
// bundler: each source file goes through sucrase with the transforms the clean
// room's tests run it with (typescript, jsx in classic mode, imports), and the
// page script holds the results in a module registry keyed by the file's path
// relative to runtime/src ("app.tsx", "index.ts"). A module's require("./x")
// resolves against that module's own folder, extensionless (x.ts, x.tsx,
// x/index.ts, x/index.tsx); "react" is the page's window.React and
// "react-dom" its window.ReactDOM (the vendored UMD builds load first); any
// other name throws. The script exposes only the host entry points, as
// window.__zrMotionRuntime = { createMotionApp, createModuleObject }.
//
// The output depends only on the source files and sucrase's version (files in
// path order, no time or machine data), so two builds are byte-identical.
//
// Usage: node packages/motion/scripts/build-runtime.mjs [--src <runtime/src>] [--out <file>]
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getVersion, transform } from "sucrase";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(PKG, "cleanroom", "runtime", "src");
const OUT = join(PKG, "dist", "zr-runtime.js");
/** The module the page's entry points come from (the runtime's host.ts). */
const ENTRY = "host.ts";

/** Every .ts/.tsx file under `dir`, as "/"-separated paths relative to `root`, in byte order. */
function sources(dir, root = dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...sources(p, root));
    else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".d.ts")) out.push(relative(root, p).split("\\").join("/"));
  }
  return out.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The page script for the runtime in `src`. */
export function buildRuntime(src = SRC) {
  const files = sources(src);
  if (!files.includes(ENTRY)) throw new Error(`${ENTRY} is missing in ${src}`);
  // The resolver below takes the first candidate; two files that both answer one request would make that a guess.
  for (const f of files) {
    const stem = f.replace(/\.tsx?$/, "");
    const rivals = files.filter((g) => g !== f && g.replace(/\.tsx?$/, "") === stem);
    if (rivals.length) throw new Error(`${f} and ${rivals.join(", ")} answer the same require`);
  }
  const modules = files.map((f) => {
    const { code } = transform(readFileSync(join(src, f), "utf8"), {
      transforms: ["typescript", "jsx", "imports"],
      jsxRuntime: "classic",
      production: true,
    });
    return `    ${JSON.stringify(f)}: function (require, exports, module) {\n${code}\n    },`;
  });
  return `// ZedMix's motion runtime as one page script. Generated by packages/motion/scripts/build-runtime.mjs
// (sucrase ${getVersion()}) from packages/motion/cleanroom/runtime/src; do not edit.
(function () {
  "use strict";
  var g = window;
  var sources = {
${modules.join("\n")}
  };
  var cache = {};

  /** The registry key for "./x" or "../x" required from module \`from\`. */
  function resolveId(from, request) {
    var parts = from.split("/").slice(0, -1);
    var steps = request.split("/");
    for (var i = 0; i < steps.length; i++) {
      if (steps[i] === "..") {
        if (!parts.length) return null;
        parts.pop();
      } else if (steps[i] !== "." && steps[i] !== "") parts.push(steps[i]);
    }
    var base = parts.join("/");
    var tries = [base + ".ts", base + ".tsx", base + "/index.ts", base + "/index.tsx"];
    for (var j = 0; j < tries.length; j++) if (Object.prototype.hasOwnProperty.call(sources, tries[j])) return tries[j];
    return null;
  }

  function load(id) {
    if (Object.prototype.hasOwnProperty.call(cache, id)) return cache[id].exports;
    var module = { exports: {} };
    // In the cache before it runs, so a cycle gets the partly filled exports (as Node does).
    cache[id] = module;
    sources[id](function (request) {
      if (request === "react") return g.React;
      if (request === "react-dom") return g.ReactDOM;
      var target = request.charAt(0) === "." ? resolveId(id, request) : null;
      if (target === null) throw new Error("zr-runtime: " + id + " requires " + JSON.stringify(request) + ", which the runtime does not have");
      return load(target);
    }, module.exports, module);
    return module.exports;
  }

  var host = load(${JSON.stringify(ENTRY)});
  Object.defineProperty(g, "__zrMotionRuntime", {
    value: Object.freeze({ createMotionApp: host.createMotionApp, createModuleObject: host.createModuleObject }),
  });
})();
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (name, fallback) => {
    const i = process.argv.indexOf(name);
    return i >= 0 ? resolve(process.argv[i + 1]) : fallback;
  };
  const out = arg("--out", OUT);
  const text = buildRuntime(arg("--src", SRC));
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`[build-runtime] wrote ${relative(process.cwd(), out) || out} (${text.length} bytes)`);
}
